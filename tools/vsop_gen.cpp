// vsop_gen: VSOP87D.ear -> C++ term tables compiled into Spp.
//
// Usage: vsop_gen <VSOP87D.ear> <output.inc>
//
// Each data line ends with the reduced coefficients A, B, C of a term
// A * cos(B + C * t). They are parsed with std::from_chars (correctly rounded)
// and written as hex-float literals, which
// the compiler reads back bit-for-bit. No decimal round trip, no drift.

#include <array>
#include <charconv>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <optional>
#include <sstream>
#include <string>
#include <string_view>
#include <system_error>
#include <vector>

namespace {

struct Term {
    double a, b, c;
};

constexpr int kVariables = 3;  // 1 = L, 2 = B, 3 = R
constexpr int kPowers = 6;     // t^0 .. t^5
constexpr std::array<char, kVariables> kNames = {'L', 'B', 'R'};

struct Header {
    int variable;  // 1..3
    int power;     // 0..5
    int count;
};

[[noreturn]] void fail(const std::string& msg) {
    std::fprintf(stderr, "vsop_gen: %s\n", msg.c_str());
    std::exit(1);
}

std::vector<std::string_view> split(std::string_view line) {
    std::vector<std::string_view> tokens;
    std::size_t i = 0;
    while (i < line.size()) {
        while (i < line.size() && (line[i] == ' ' || line[i] == '\t' || line[i] == '\r')) ++i;
        std::size_t j = i;
        while (j < line.size() && line[j] != ' ' && line[j] != '\t' && line[j] != '\r') ++j;
        if (j > i) tokens.push_back(line.substr(i, j - i));
        i = j;
    }
    return tokens;
}

template <class T>
T parse(std::string_view tok, const std::string& where) {
    T value{};
    auto [ptr, ec] = std::from_chars(tok.data(), tok.data() + tok.size(), value);
    if (ec != std::errc{} || ptr != tok.data() + tok.size())
        fail("bad number '" + std::string(tok) + "' at " + where);
    return value;
}

// " VSOP87 VERSION D4  EARTH  VARIABLE 1 (LBR)  *T**0  559 TERMS  ..."
std::optional<Header> parse_header(std::string_view line, const std::string& where) {
    auto tokens = split(line);
    if (tokens.size() < 2 || tokens[0] != "VSOP87" || tokens[1] != "VERSION") return std::nullopt;

    Header h{-1, -1, -1};
    for (std::size_t i = 0; i < tokens.size(); ++i) {
        if (tokens[i] == "VARIABLE" && i + 1 < tokens.size())
            h.variable = parse<int>(tokens[i + 1], where);
        else if (tokens[i].starts_with("*T**"))
            h.power = parse<int>(tokens[i].substr(4), where);
        else if (tokens[i] == "TERMS" && i > 0)
            h.count = parse<int>(tokens[i - 1], where);
    }
    if (h.variable < 1 || h.variable > kVariables) fail("bad VARIABLE at " + where);
    if (h.power < 0 || h.power >= kPowers) fail("bad power at " + where);
    if (h.count <= 0) fail("bad term count at " + where);
    return h;
}

std::string hex_literal(double x) {
    std::array<char, 64> buf{};
    bool negative = x < 0.0;
    auto [ptr, ec] = std::to_chars(buf.data(), buf.data() + buf.size(),
                                   negative ? -x : x, std::chars_format::hex);
    if (ec != std::errc{}) fail("to_chars failed");
    return (negative ? "-0x" : "0x") + std::string(buf.data(), ptr);
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 3) fail("usage: vsop_gen <VSOP87D.ear> <output.inc>");

    std::ifstream in(argv[1]);
    if (!in) fail(std::string("cannot open ") + argv[1]);

    std::array<std::array<std::optional<std::vector<Term>>, kPowers>, kVariables> blocks;

    std::string line;
    int line_no = 0;
    while (std::getline(in, line)) {
        ++line_no;
        auto header = parse_header(line, "line " + std::to_string(line_no));
        if (!header) {
            if (!split(line).empty()) fail("unexpected content at line " + std::to_string(line_no));
            continue;
        }

        auto& slot = blocks[header->variable - 1][header->power];
        if (slot) fail("duplicate block at line " + std::to_string(line_no));
        slot.emplace();
        slot->reserve(static_cast<std::size_t>(header->count));

        for (int k = 0; k < header->count; ++k) {
            if (!std::getline(in, line)) fail("truncated block ending at line " + std::to_string(line_no));
            ++line_no;
            std::string where = "line " + std::to_string(line_no);
            auto tokens = split(line);
            if (tokens.size() < 5) fail("short data line at " + where);
            std::size_t n = tokens.size();
            slot->push_back({parse<double>(tokens[n - 3], where),
                             parse<double>(tokens[n - 2], where),
                             parse<double>(tokens[n - 1], where)});
        }
    }

    std::ostringstream out;
    out << "// Generated by tools/vsop_gen from data/VSOP87D.ear. Do not edit.\n"
        << "// Terms are A * cos(B + C * t); literals are exact hex floats.\n\n"
        << "namespace spp::model::vsop87d::data {\n\n";

    int total = 0;
    for (int v = 0; v < kVariables; ++v) {
        for (int p = 0; p < kPowers; ++p) {
            const auto& block = blocks[v][p];
            if (!block) continue;
            total += static_cast<int>(block->size());
            out << "inline constexpr Term " << kNames[v] << p << "[" << block->size() << "] = {\n";
            for (const Term& t : *block)
                out << "    {" << hex_literal(t.a) << ", " << hex_literal(t.b) << ", "
                    << hex_literal(t.c) << "},\n";
            out << "};\n\n";
        }
    }

    for (int v = 0; v < kVariables; ++v) {
        out << "inline constexpr std::span<const Term> " << kNames[v] << "[" << kPowers << "] = {";
        for (int p = 0; p < kPowers; ++p) {
            if (p) out << ", ";
            if (blocks[v][p]) out << kNames[v] << p;
            else out << "{}";
        }
        out << "};\n";
    }
    out << "\n}  // namespace spp::model::vsop87d::data\n";

    std::ofstream file(argv[2], std::ios::binary);
    if (!file) fail(std::string("cannot write ") + argv[2]);
    file << out.str();

    std::printf("vsop_gen: %d terms written to %s\n", total, argv[2]);
    return 0;
}
