#!/usr/bin/env python3
"""Build the embedded UI font atlas with ImageMagick; no runtime font dependency."""
import argparse
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("font", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
width, height, cell_width, cell_height = 384, 192, 24, 32
command = ["magick", "-size", f"{width}x{height}", "xc:black", "-font", str(args.font),
           "-pointsize", "20", "-fill", "white"]
advances = []
for i in range(96):
    char = chr(i + 32) if i < 95 else "?"
    escaped = char.replace("\\", "\\\\").replace("'", "\\'")
    command += ["-draw", f"text {(i%16)*cell_width+1},{(i//16)*cell_height+24} '{escaped}'"]
    advances.append(12.1)  # 20 px DejaVu Sans Mono; small positive tracking
command += ["-depth", "8", "gray:-"]
pixels = subprocess.run(command, check=True, capture_output=True).stdout
if len(pixels) != width*height:
    raise RuntimeError("unexpected ImageMagick grayscale atlas size")
encoded = []
for value in pixels:
    if encoded and encoded[-1] == value and encoded[-2] < 255:
        encoded[-2] += 1
    else:
        encoded.extend((1, value))
lines = ["// Generated by tools/font_atlas.py from DejaVu Sans Mono, 20 px.",
         "// Font copyright/license: data/licenses/DejaVu.txt", "#pragma once",
         "#include <array>", "namespace spp::app::font {",
         f"inline constexpr int width={width}, height={height}, cell_width={cell_width}, cell_height={cell_height};",
         "inline constexpr std::array<float,96> advance={" + ",".join(f"{v:.6f}f" for v in advances) + "};",
         "inline constexpr unsigned char rle[]={"]
lines += [",".join(str(v) for v in encoded[i:i+48])+"," for i in range(0,len(encoded),48)]
lines += ["};", "}  // namespace spp::app::font", ""]
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text("\n".join(lines))
print(f"Embedded font: {len(encoded)} RLE bytes, {width} x {height}")
