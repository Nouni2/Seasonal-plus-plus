#!/usr/bin/env python3
"""Regenerate reference states from an unmodified ytliu0/ElpMpp02 checkout.

Use revision e25e08f6082a3f3211b3d14e062d935558ad3ea6, not Spp's evaluator.
This development-only tool compiles and runs that upstream implementation.
It performs no downloads. The production build needs neither Python nor it.
"""
import argparse
import hashlib
import json
import pathlib
import random
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("upstream", type=pathlib.Path)
parser.add_argument("output", type=pathlib.Path)
parser.add_argument("--cxx", default="g++")
args = parser.parse_args()
upstream = args.upstream.resolve()
# Refuse to label results as this revision when a different evaluator or
# coefficient set was supplied. No Git checkout or network access is needed.
for name, expected in {
    "ElpMpp02.cpp": "a0b159150a92ab729cab830a5d67f5743a8c6513",
    "ElpMpp02.h": "2c9afe2f9f3ecf434b4d775a4613241867ee28ee",
}.items():
    contents = (upstream / name).read_bytes()
    blob = b"blob " + str(len(contents)).encode() + b"\0" + contents
    if hashlib.sha1(blob).hexdigest() != expected:
        parser.error(f"{name} is not from the pinned upstream revision")
manifest = json.loads((pathlib.Path(__file__).resolve().parents[1]
                       / "data/elp_mpp02/manifest.json").read_text())
for name, entry in manifest["files"].items():
    if hashlib.sha256((upstream / name).read_bytes()).hexdigest() != entry["sha256"]:
        parser.error(f"{name} does not match the pinned coefficient data")
rng = random.Random(20261103)
epochs = [(2451545, 0.0), (2451545, 0.5), (2444239, 0.5), (2452239, 0.5),
          (1700000, 0.5), (2500000, 0.5), (1319270, 0.0), (2853320, 0.0)]
epochs += [(rng.randrange(1319270, 2853320), rng.randrange(1024) / 1024)
           for _ in range(64)]
driver = r'''
#include "ElpMpp02.h"
#include <cstdio>
int main() {
    for (int fit = 0; fit < 2; ++fit) {
        Elp_paras parameters;
        Elp_facs factors;
        Elp_coefs coefficients;
        setup_parameters(fit, parameters, factors);
        setup_Elp_coefs(coefficients, factors);
        long long day;
        double fraction;
        while (std::scanf("%lld %lf", &day, &fraction) == 2) {
            double state[6];
            const double t = (static_cast<double>(day - 2451545) + fraction) / 36525.0;
            getX2000_Xdot2000(t, parameters, coefficients, state);
            std::printf("%d,%lld,%.17g", fit, day, fraction);
            for (double value : state) std::printf(",%.17g", value);
            std::printf("\n");
        }
        // stdin is a regular temporary file so each fitted set uses the same epochs.
        std::rewind(stdin);
    }
}
'''
with tempfile.TemporaryDirectory(prefix="spp-lunar-reference-") as tmp:
    work = pathlib.Path(tmp)
    (work / "reference.cpp").write_text(driver)
    executable = work / "reference"
    subprocess.run([args.cxx, "-std=c++20", "-O2", "-ffp-contract=off",
                    "-fno-fast-math", "-I", str(upstream),
                    str(upstream / "ElpMpp02.cpp"), str(work / "reference.cpp"),
                    "-o", str(executable)], check=True)
    inputs = work / "epochs.txt"
    inputs.write_text("".join(f"{day} {fraction:.17g}\n" for day, fraction in epochs))
    with inputs.open() as stream:
        result = subprocess.run([str(executable)], cwd=upstream, stdin=stream,
                                capture_output=True, text=True, check=True)
    args.output.write_text(
        "# ytliu0/ElpMpp02 e25e08f6082a3f3211b3d14e062d935558ad3ea6\n"
        "# Generated by tools/lunar_reference.py with upstream getX2000_Xdot2000.\n"
        "# fit(0=LLR,1=DE405),TDB day,fraction,x_km,y_km,z_km,vx_km_day,vy_km_day,vz_km_day\n"
        + result.stdout)
print(f"Wrote {len(epochs) * 2} independent reference states to {args.output}")
