"""Generates src/model/delta_t_observed.hpp from IERS data.

Observed ΔT = TT - UT1 on the 1st of every month at 0h UTC, from 1972-01-01 to
the last month in the series:

    ΔT = 32.184 s + (TAI - UTC) - (UT1 - UTC)

with UT1 - UTC from the IERS EOP 20 C04 series (eopc04.1962-now, daily at 0h
UTC) and TAI - UTC from the IERS leap-second file (Leap_Second.dat). Both are
published by the IERS Earth Orientation Centre:
    https://hpiers.obspm.fr/iers/eop/eopc04/eopc04.1962-now
    https://hpiers.obspm.fr/iers/bul/bulc/Leap_Second.dat

Usage: python3 tools/delta_t_table.py eopc04.1962-now Leap_Second.dat > src/model/delta_t_observed.hpp
"""

import sys
from decimal import Decimal


def leap_seconds(path):
    steps = []
    for line in open(path):
        if line.startswith("#") or not line.strip():
            continue
        p = line.split()
        steps.append((int(float(p[0])), int(p[4])))
    return steps


def tai_minus_utc(steps, mjd):
    value = None
    for start, v in steps:
        if mjd >= start:
            value = v
    return value


def main():
    eop_path, leap_path = sys.argv[1], sys.argv[2]
    steps = leap_seconds(leap_path)
    header = [line.rstrip("\n") for line in open(eop_path) if line.startswith("#")][:2]
    rows = []
    last_date = None
    for line in open(eop_path):
        if line.startswith("#") or not line.strip():
            continue
        p = line.split()
        y, m, d = int(p[0]), int(p[1]), int(p[2])
        last_date = (y, m, d)
        if d != 1 or y < 1972:
            continue
        mjd = int(float(p[4]))
        ut1_utc = Decimal(p[7])
        dt = Decimal("32.184") + tai_minus_utc(steps, mjd) - ut1_utc
        rows.append((mjd, y, m, dt))

    out = sys.stdout
    first, last = rows[0], rows[-1]
    out.write("#pragma once\n\n")
    out.write("// Observed ΔT = TT - UT1 in seconds on the 1st of every month at 0h UTC,\n")
    out.write(f"// {first[1]}-{first[2]:02d} to {last[1]}-{last[2]:02d}, keyed by MJD (UTC):\n")
    out.write("//     ΔT = 32.184 s + (TAI - UTC) - (UT1 - UTC)\n")
    out.write("// UT1 - UTC: IERS EOP 20 C04 (eopc04.1962-now), series up to "
              f"{last_date[0]}-{last_date[1]:02d}-{last_date[2]:02d}.\n")
    out.write("// TAI - UTC: IERS Leap_Second.dat.\n")
    out.write("// Generated by tools/delta_t_table.py; do not edit by hand.\n\n")
    out.write("namespace spp::model::espenak_meeus::detail {\n\n")
    out.write("struct ObservedDeltaT {\n    int mjd;\n    double seconds;\n};\n\n")
    out.write("inline constexpr ObservedDeltaT kObservedDeltaT[] = {\n")
    for i in range(0, len(rows), 4):
        chunk = rows[i:i + 4]
        cells = ", ".join(f"{{{mjd}, {dt}}}" for mjd, _, _, dt in chunk)
        out.write(f"    {cells},   // {chunk[0][1]}-{chunk[0][2]:02d}\n")
    out.write("};\n\n}  // namespace spp::model::espenak_meeus::detail\n")


if __name__ == "__main__":
    main()
